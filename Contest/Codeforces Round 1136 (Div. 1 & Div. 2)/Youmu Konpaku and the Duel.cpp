#pragma GCC optimize("O3")
#pragma GCC optimize("unroll-loops")

using ll = long long;

const ll INF = (ll) 4e18;
const ll NEG = -INF;
const int MOD = 1'000'000'007;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        int x, ans = 0, best = 0; cin >> x;
        while (best < x) {
            ans++;
            for (int c = 0; c < ans; c++) {
                int a = ans - c, k = min(a, c);
                best = max(best, a + k * (2 * c - k + 1) / 2);
            }
        }
        cout << ans << '\n';
    }
}