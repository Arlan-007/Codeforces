using ll = long long;

const ll INF = (ll) 4e18;
const ll NEG = -INF;
const int MOD = 1'000'000'007;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) {
        ll x, y, k, ans =0; cin >> x >> y >> k;

        ll a = y - x;
        if (y < 2 * x) ans = k * a;
        else {
            ll blk = min(k - 1, a - x);
            ans += (k - blk - 1) * a;
            for (ll i = 0; i <= blk; i++) ans += a % (x + i);
        }
        cout << ans << '\n';
    }
}