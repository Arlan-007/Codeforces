int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        int a, b; cin >> a >> b;
        int ans = -1;
        if (a == 0) {
            if (b == 0) ans = 0;
            else if (abs(b) == 1) ans = 1;
        } else if (a > 0 && abs(b) <= a + 1) ans = abs(b - a) % 2 == 0 ? a : a + 1;
        cout << ans << "\n";
    }
}