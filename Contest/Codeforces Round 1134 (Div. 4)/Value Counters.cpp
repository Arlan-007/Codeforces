const ll NEG = -INF;
const int MOD = 1'000'000'007;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        int n, b, pos; cin >> n;
        vector<int> p(n, 0);
        bool ok = true;

        for (int x = 1; x <= n; x++) {
            cin >> b, pos = b + n - x;
            if (pos < 0 || pos >= n || p[pos]) ok = false;
            else p[pos] = x;
        }

        if (!ok) cout << -1;
        else for (int x : p) cout << x << ' ';
        cout << '\n';
    }
}