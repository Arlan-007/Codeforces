using ll = long long;

const ll INF = (ll) 4e18;
const ll NEG = -INF;
const int MOD = 1'000'000'007;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--) {
        int n; cin >> n;
        vector<ll> a(n) , c(n, 0);
        for(auto &x : a) cin >> x;

        for(int i = 0; i < n ; i++){
            for(int j = 0; j <= i ; j++){
                ll &x = c[j];
                if(x >= a[i]) x -= a[i];
                else x += a[i];
            }
        }

        for(int i = n-1 ; i >= 0 ; i--) cout << c[i] << " ";
        cout << '\n';
    }
}