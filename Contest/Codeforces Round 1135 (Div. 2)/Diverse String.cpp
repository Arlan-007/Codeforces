int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        ll n, k, x = 0; cin >> n >> k;
        string s; cin >> s;
        for (char c : s) if (c == '0') x++;
        x = min(max(x, n - x) + k, n);
        cout << x * (x + 1) / 2 + (n - x) * (n - x + 1) / 2 + 1 << '\n';
    }
}