int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);

    int t;
    cin >> t;
    while (t--) {
        int m, x, use = 0; cin >> m >> x;
        priority_queue<int> pq;
        for (int i = 0; i < m; i++) {
            int c; cin >> c;
            pq.push(c), use += c;
            if (use > i * x) use -= pq.top(), pq.pop();
        }
        cout << pq.size() << '\n';
    }
}